// Find a job by the label shown on a stream card
export function findJob(label) {
  const l = String(label).trim().toLowerCase();
  return JOBS.find((j) => j.name.toLowerCase() === l || j.aliases.some((a) => a.toLowerCase() === l)) || null;
}
